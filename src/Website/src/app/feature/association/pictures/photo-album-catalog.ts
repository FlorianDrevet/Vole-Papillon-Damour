export interface PhotoAlbum {
  slug: string;
  title: string;
  eyebrow: string;
  description: string;
  category: 'maxence' | 'evenements';
  photos: readonly string[];
  previewPhotos: readonly string[];
}

export const PHOTO_ALBUMS_ROUTE = '/association/photos';

type PhotoAlbumCategory = Readonly<{
  id: PhotoAlbum['category'];
  eyebrow: string;
  title: string;
  description: string;
  albums: readonly PhotoAlbum[];
}>;

function createPhotoAlbum(
  slug: string,
  title: string,
  eyebrow: string,
  description: string,
  category: PhotoAlbum['category'],
  photos: readonly string[],
): PhotoAlbum {
  return {
    slug,
    title,
    eyebrow,
    description,
    category,
    photos,
    previewPhotos: photos.slice(0, 3),
  };
}

